"""Import the 32x32 pixel-food pack and build a recipe -> image manifest.

Usage (from what_to_eat/):
    python tools/import_pixel_food.py
    python tools/import_pixel_food.py --source "C:/Users/user/Desktop/food"

The source folder is not modified. Files are copied byte-for-byte when they are
already 32x32 RGBA; otherwise they are converted to RGBA and re-saved.
"""

from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = Path.home() / "Desktop" / "food"
DEST = ROOT / "assets" / "pixel_food"

# Only use images whose subject is close enough to the actual dish.
# The rest deliberately fall back to the procedural FoodArt, so we never show
