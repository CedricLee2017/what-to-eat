def import_pack(source: Path) -> None:
    if not source.is_dir():
        raise SystemExit(f"missing source folder: {source}")
    files = sorted(path for path in source.iterdir() if path.suffix.lower() == ".png")
    if not files:
        raise SystemExit(f"no PNG files in {source}")

    DEST.mkdir(parents=True, exist_ok=True)
    copied = 0
    for path in files:
        with Image.open(path) as image:
            size = image.size
            mode = image.mode
        if size != (32, 32):
            raise SystemExit(f"{path.name}: expected 32x32, got {size[0]}x{size[1]}")
        target = DEST / path.name
        if mode == "RGBA":
            shutil.copy2(path, target)
        else:
            with Image.open(path) as image:
                image.convert("RGBA").save(target, "PNG")
        copied += 1

    missing = [name for name, _ in RECIPE_IMAGES.values() if not (DEST / name).is_file()]
    if missing:
        raise SystemExit(f"mapping references missing files: {missing}")

    manifest = {
        "style": "pixel-art",
        "tile_size": 32,
        "source": "Desktop/food",
        "recipes": {
            recipe_id: {"file": file_name, "label": label}
            for recipe_id, (file_name, label) in sorted(RECIPE_IMAGES.items())
        },
        "all_files": [path.name for path in files],
    }
    manifest_path = DEST / "manifest.json"
    manifest_path.write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )

    mapping_path = DEST / "MAPPING.md"
    lines = [
        "# Pixel food mapping",
        "",
        "Generated by `tools/import_pixel_food.py`. Edit `RECIPE_IMAGES` there, not this file.",
        "",
        "| Recipe | File |",
        "| --- | --- |",
    ]
    for recipe_id, (file_name, label) in sorted(RECIPE_IMAGES.items()):
        lines.append(f"| `{recipe_id}`（{label}） | `{file_name}` |")
    lines.append("")
    lines.append(f"Imported {copied} files from `{source}`.")
    mapping_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"copied {copied} pixel-food files -> {DEST}")
    print(f"mapped {len(RECIPE_IMAGES)} recipes")
    print(f"manifest: {manifest_path}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    args = parser.parse_args()
    import_pack(args.source)


if __name__ == "__main__":
    main()
